def equivalent(actual, expected):
    if isinstance(expected, dict):
        return isinstance(actual, dict) and actual.keys()==expected.keys() and all(equivalent(actual[k],v) for k,v in expected.items())
    if isinstance(expected,(tuple,list)):
        return isinstance(actual,(tuple,list)) and len(actual)==len(expected) and all(equivalent(a,b) for a,b in zip(actual,expected))
    if isinstance(expected,(int,float)) and not isinstance(expected,bool):
        return isinstance(actual,(int,float)) and (actual==expected or math.isclose(actual,expected,rel_tol=1e-6,abs_tol=1e-7))
    return type(actual) is type(expected) and actual==expected

def evaluate(function,case):
    title,args,expected=case
    got=function(*copy.deepcopy(args))
    return None if equivalent(got,expected) else f'{title}: returned {short(got,100)}, expected {short(expected,100)}.'

